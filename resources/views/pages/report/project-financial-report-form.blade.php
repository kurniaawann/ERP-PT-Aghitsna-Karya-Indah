{{-- =====================================================================
     Halaman: Form Tambah Transaksi / Edit Laporan Keuangan Proyek
     Tujuan: Pengganti modal Tambah Transaksi & modal Edit gabungan (Rekap
             Proyek + transaksi "Bon") pada halaman daftar.

     Data dari ProjectFinancialReportController@create / @edit:
     - $recap        : ProjectRecap (edit, + financialReport.items) | null (tambah)
     - $categories   : kategori transaksi modul Keuangan Proyek
     - $rekapOptions : pilihan Rekap Proyek + sisa pembayaran (tambah)
     - $executives   : Data Penandatangan milik user (edit)

     Submit:
     - Tambah → route('project-financial-report.store') (POST)
     - Edit   → route('project-financial-report.update', $recap) (PUT)
     Berhasil → daftar Laporan Keuangan Proyek. Gagal validasi → kembali ke
     halaman ini (tambah: transaksi yang sudah diisi dipulihkan dari old()).

     Struktur transaksi dibuat JS (1 kategori = banyak keterangan/bon) di
     kontainer #transactionsContainer (tambah) / #transactionsContainer-{id}
     (edit) — id turunan: -totalIncome, -totalExpense, -balance, -incomeWarning.

     JS: @vite('resources/js/pages/report/project-financial-report/form.js')
     ===================================================================== --}}
@extends('layouts.app')

@php
    $isEdit = (bool) $recap;
    $indexUrl = route('project-financial-report.index');
    $containerId = $isEdit ? 'transactionsContainer-' . $recap->id : 'transactionsContainer';

    $report = $recap?->financialReport;
    $existingItems = optional($report)->items ?? collect();

    $categoriesJson = $categories->map(fn ($cat) => [
        'id' => $cat->id,
        'name' => $cat->name,
        'type' => $cat->type,
    ])->values()->toJson();

    // Edit: transaksi tersimpan (dikelompokkan per kategori oleh JS)
    $existingItemsJson = $existingItems->map(fn ($item) => [
        'id' => $item->id,
        'payment_proof_id' => $item->payment_proof_id,
        'is_informational' => $item->is_informational,
        'is_auto' => $item->isAutoGenerated(),
        'auto_source' => str_starts_with((string) $item->description, 'Upah Kerja')
            ? 'payroll'
            : (str_starts_with((string) $item->description, 'Kasbon Divisi') ? 'kasbon' : null),
        'transaction_category_id' => $item->transaction_category_id,
        'transaction_date' => $item->transaction_date ? \Carbon\Carbon::parse($item->transaction_date)->format('Y-m-d') : '',
        'description' => $item->description,
        'amount' => (int) ($item->income_amount ?: $item->expense_amount),
        'keterangan_bon' => $item->keterangan_bon,
        'proof_file' => $item->proof_file,
        'proof_file_name' => $item->proof_file_name,
        'proof_url' => $item->proof_file ? asset('storage/' . $item->proof_file) : null,
    ])->values()->toJson();

    // Tambah: transaksi yang sudah diisi saat gagal simpan (file bukti tidak bisa dipulihkan)
    $oldItemsJson = collect($isEdit ? [] : (array) old('items', []))
        ->filter(fn ($item) => is_array($item))
        ->map(fn ($item) => [
            'transaction_category_id' => $item['transaction_category_id'] ?? '',
            'transaction_date' => $item['transaction_date'] ?? '',
            'description' => $item['description'] ?? '',
            'amount' => $item['expense_amount'] ?? '',
            'keterangan_bon' => $item['keterangan_bon'] ?? '',
        ])->values()->toJson();

    $remainingAmount = $isEdit ? $recap->getRemainingAmount() : null;

    $signatureRoles = [
        'mandor' => 'Mandor',
        'kabag_keuangan' => 'Kabag Keuangan',
        'direktur' => 'Direktur PT. Aghitsna Karya Indah',
    ];
    $storedSignatures = $isEdit
        ? app(\App\Services\Report\ProjectFinancialReportService::class)->getReportSignatures($report)
        : [];
    $storedSignatures = is_array($storedSignatures) ? $storedSignatures : [];

    $rupiah = fn ($value) => 'Rp ' . number_format($value, 0, ',', '.');
@endphp

@section('title', 'PT Aghitsna Karya Indah - ' . ($isEdit ? 'Edit Laporan Keuangan Proyek' : 'Tambah Transaksi'))

@section('content')
    <div class="flex flex-col gap-y-6">

        {{-- SECTION: Header Halaman --}}
        <x-fi.page-header :heading="$isEdit ? 'Edit — ' . $recap->project_name : 'Tambah Transaksi'"
            :breadcrumbs="['Report' => null, 'Laporan Keuangan Proyek' => $indexUrl, ($isEdit ? 'Edit' : 'Tambah Transaksi') => null]" />

        {{-- SECTION: Ringkasan error validasi server --}}
        <x-fi.validation-errors />

        <form id="pfr-form" method="POST" enctype="multipart/form-data" data-mode="{{ $isEdit ? 'edit' : 'create' }}"
            action="{{ $isEdit ? route('project-financial-report.update', $recap) : route('project-financial-report.store') }}"
            class="flex flex-col gap-y-6">
            @csrf
            @if ($isEdit)
                @method('PUT')
            @endif

            {{-- Desktop: Data + Ringkasan, lalu Transaksi & Penanda Tangan (lebar penuh).
                 Mobile: Data → Transaksi → Ringkasan → Penanda Tangan. --}}
            <div class="grid grid-cols-1 gap-6 lg:grid-cols-3">

                @if ($isEdit)
                    {{-- SECTION: Data Rekap Proyek --}}
                    <x-fi.section heading="Data Rekap Proyek" class="lg:col-span-2">
                        <div class="grid grid-cols-1 gap-x-4 gap-y-5 sm:grid-cols-2">

                            {{-- Field: ID Rekap (tidak dapat diubah) --}}
                            <x-fi.field label="ID Rekap Proyek">
                                <x-fi.input :value="$recap->id" prefix-icon="lock-closed" aria-label="ID Rekap Proyek" readonly />
                            </x-fi.field>

                            {{-- Field: Nama Proyek --}}
                            <x-fi.field label="Nama Proyek" for="project-name" required>
                                <x-fi.input id="project-name" name="project_name" :value="old('project_name', $recap->project_name)"
                                    required maxlength="255"
                                    oninvalid="this.setCustomValidity('Nama proyek tidak boleh kosong')" oninput="this.setCustomValidity('')" />
                            </x-fi.field>

                            {{-- Field: Lokasi --}}
                            <x-fi.field label="Lokasi" for="project-location">
                                <x-fi.input id="project-location" name="location" :value="old('location', $recap->location)" maxlength="255" />
                            </x-fi.field>

                            {{-- Field: Total RAB (terkunci bila rekap dibuat dari RAB) --}}
                            @if ($recap->rab_number)
                                <x-fi.field label="Total RAB" required
                                    :hint="'Total RAB mengikuti RAB sumber (' . $recap->rab_number . '). Ubah di modul RAB.'">
                                    <x-fi.input :value="number_format($recap->rab?->total_amount ?? $recap->total_rab ?? 0, 0, ',', '.')"
                                        prefix="Rp" suffix="Terkunci" aria-label="Total RAB" readonly disabled />
                                    <input type="hidden" name="total_rab" value="{{ $recap->rab?->total_amount ?? $recap->total_rab ?? 0 }}">
                                </x-fi.field>
                            @else
                                <x-fi.field label="Total RAB" for="total-rab" required>
                                    <x-fi.input id="total-rab" inputmode="numeric" name="total_rab" class="total-rab-input" prefix="Rp"
                                        :value="number_format((int) preg_replace('/[^0-9]/', '', (string) old('total_rab', $recap->total_rab ?? 0)), 0, ',', '.')"
                                        required min="0"
                                        oninvalid="this.setCustomValidity('Total RAB tidak boleh kosong')" oninput="this.setCustomValidity('')" />
                                </x-fi.field>
                            @endif

                            {{-- File Design Saat Ini (pratinjau di dalam halaman, tanpa tab baru) --}}
                            @if ($recap->hasDesignFile())
                                <x-fi.field label="File Design Saat Ini" class="sm:col-span-2">
                                    <a href="{{ asset('storage/' . $recap->design_file) }}"
                                        onclick="event.preventDefault(); window.openFilePreview(this.href, { title: @js('File Design — ' . $recap->project_name), downloadName: @js($recap->design_file_name ?: basename($recap->design_file)) })"
                                        class="inline-flex max-w-full items-center gap-1.5 justify-self-start text-sm font-medium text-primary hover:underline">
                                        <x-fi.icon name="photo" class="h-4 w-4 shrink-0" />
                                        <span class="truncate">{{ $recap->design_file_name }}</span>
                                    </a>
                                </x-fi.field>
                            @endif
                        </div>
                    </x-fi.section>
                @else
                    {{-- SECTION: Rekap Proyek tujuan --}}
                    <x-fi.section heading="Rekap Proyek" class="lg:col-span-2">
                        <x-fi.field label="Rekap Proyek" for="project-recap-id" required>
                            <x-fi.select id="project-recap-id" name="project_recap_id" prefix-icon="building-office-2"
                                placeholder="-- Pilih Rekap Proyek --" required data-fi-select="search"
                                oninvalid="this.setCustomValidity('Rekap Proyek tidak boleh kosong')" oninput="this.setCustomValidity('')">
                                @foreach ($rekapOptions as $rekap)
                                    <option value="{{ $rekap['id'] }}" data-remaining-amount="{{ $rekap['remaining_amount'] }}"
                                        @selected((string) old('project_recap_id') === (string) $rekap['id'])>
                                        {{ $rekap['id'] }} — {{ $rekap['project_name'] }}{{ $rekap['location'] ? ' (' . $rekap['location'] . ')' : '' }}
                                    </option>
                                @endforeach
                            </x-fi.select>

                            @if ($rekapOptions->isEmpty())
                                <p class="text-sm text-red-600">
                                    Belum ada Rekap Proyek. Buat rekap terlebih dahulu melalui menu
                                    <a href="{{ route('recap-proyek.index') }}" class="font-medium underline">Rekap Proyek</a>.
                                </p>
                            @endif
                        </x-fi.field>
                    </x-fi.section>
                @endif

                {{-- SECTION: Ringkasan (dihitung ulang form.js setiap transaksi berubah) --}}
                <x-fi.section heading="Ringkasan" class="order-1 self-start lg:order-none">
                    <dl class="grid gap-y-3 text-sm">
                        @if ($isEdit)
                            <div class="flex items-center justify-between gap-3">
                                <dt class="text-gray-500">No. Laporan</dt>
                                <dd><x-fi.badge color="primary" icon="document-currency-dollar">{{ $report->id ?? 'Belum dibuat' }}</x-fi.badge></dd>
                            </div>
                        @endif
                        <div class="flex items-center justify-between gap-3">
                            <dt class="text-gray-500">Sisa pembayaran proyek</dt>
                            <dd class="font-medium tabular-nums text-gray-950" data-summary="remaining">
                                {{ $isEdit ? $rupiah($remainingAmount) : '-' }}
                            </dd>
                        </div>
                        <div class="flex items-center justify-between gap-3">
                            <dt class="text-gray-500">Total Pemasukan</dt>
                            <dd id="{{ $containerId }}-totalIncome" class="font-medium tabular-nums text-emerald-600">Rp 0</dd>
                        </div>
                        <div class="flex items-center justify-between gap-3">
                            <dt class="text-gray-500">Total Pengeluaran</dt>
                            <dd id="{{ $containerId }}-totalExpense" class="font-medium tabular-nums text-red-600">Rp 0</dd>
                        </div>
                        <div class="flex items-center justify-between gap-3 border-t border-gray-200 pt-3">
                            <dt class="font-semibold text-gray-950">Saldo</dt>
                            <dd id="{{ $containerId }}-balance" class="text-base font-semibold tabular-nums text-gray-950">Rp 0</dd>
                        </div>
                    </dl>
                </x-fi.section>

                {{-- SECTION: Detail Transaksi (struktur dinamis: 1 kategori = banyak keterangan/bon) --}}
                <x-fi.section heading="Detail Transaksi" description="Pilih kategori, lalu isi satu atau beberapa keterangan (bon) di dalamnya."
                    class="lg:col-span-3">
                    <div class="grid gap-y-4">

                        {{-- Petunjuk struktur --}}
                        <div class="grid gap-y-1.5 rounded-lg bg-gray-50 p-4 text-sm text-gray-600">
                            <p><span class="font-semibold text-gray-950">Struktur:</span> Pilih Kategori lalu klik
                                <span class="font-semibold text-gray-950">Tambah Keterangan</span> untuk mengisi satu atau banyak
                                keterangan dalam kategori yang sama.</p>
                            <p>Kategori <span class="font-semibold text-emerald-600">Pemasukan</span> otomatis menjadi
                                <span class="font-semibold text-gray-950">Jumlah Pemasukan</span>, kategori
                                <span class="font-semibold text-red-600">Pengeluaran</span> otomatis menjadi
                                <span class="font-semibold text-gray-950">Jumlah Pengeluaran</span>.</p>
                            @if ($isEdit)
                                <p>Hapus blok keterangan untuk menghapus bon, atau hapus kategori untuk menghapus seluruh keterangannya.</p>
                                <p class="flex gap-x-2 text-amber-700">
                                    <x-fi.icon name="lock-closed" class="mt-0.5 h-4 w-4 shrink-0" />
                                    <span>Transaksi otomatis dari Bukti Pembayaran, Upah Kerja (Payroll), dan Kasbon Divisi tidak dapat
                                        dihapus di sini — hapus lewat modul sumbernya (Bukti Pembayaran, Payroll, atau Kasbon).</span>
                                </p>
                                <p class="flex gap-x-2 text-amber-700">
                                    <x-fi.icon name="lock-closed" class="mt-0.5 h-4 w-4 shrink-0" />
                                    <span>Uang masuk dari Bukti Pembayaran (rekap maupun Invoice Proyek yang ditautkan ke rekap ini)
                                        hanya bisa diubah keterangannya — nominal, tanggal, dan file buktinya selalu mengikuti bukti
                                        pembayaran. Pembayaran invoice dicatat tanpa PPN (sebanding Total RAB).</span>
                                </p>
                            @endif
                        </div>

                        @if ($isEdit && $existingItems->isEmpty())
                            <p id="emptyTransactionsHint-{{ $recap->id }}" class="text-sm text-gray-500">
                                Belum ada transaksi. Klik "Tambah Kategori" di bawah untuk menambahkan.
                            </p>
                        @endif

                        {{-- Kontainer Transaksi (diisi form.js) --}}
                        <div id="{{ $containerId }}" class="grid gap-4"
                            data-categories="{{ $categoriesJson }}"
                            @if ($isEdit)
                                data-existing-items="{{ $existingItemsJson }}"
                                data-remaining-amount="{{ $remainingAmount }}"
                                data-remaining-amount-base="{{ $remainingAmount }}"
                                data-original-total-rab="{{ $recap->total_rab }}"
                            @else
                                data-old-items="{{ $oldItemsJson }}"
                            @endif
                        ></div>

                        {{-- Peringatan pemasukan melebihi sisa pembayaran (diisi form.js) --}}
                        <div id="{{ $containerId }}-incomeWarning"
                            class="hidden rounded-lg bg-red-50 p-3 text-sm font-medium text-red-700 ring-1 ring-inset ring-red-600/20"></div>

                        <button type="button" onclick="addTransactionCategoryGroup('{{ $containerId }}')"
                            class="inline-flex w-full items-center justify-center gap-1.5 rounded-lg border border-dashed border-gray-300 px-3 py-2.5 text-sm font-semibold text-gray-700 transition duration-75 hover:border-primary hover:bg-gray-50 hover:text-primary">
                            <x-fi.icon name="plus" class="h-5 w-5" />
                            Tambah Kategori
                        </button>
                    </div>
                </x-fi.section>

                {{-- SECTION: Penanda Tangan (edit; dari Data Penandatangan) --}}
                @if ($isEdit)
                    <x-fi.section heading="Penanda Tangan"
                        description="Opsional — data diambil dari modul Data Penandatangan; jika dikosongkan, blok tanda tangan pada cetakan PDF/Excel tidak menampilkan nama."
                        class="order-2 lg:order-none lg:col-span-3">
                        <div class="grid grid-cols-1 gap-x-4 gap-y-5 md:grid-cols-3">
                            @foreach ($signatureRoles as $roleKey => $roleLabel)
                                @php $selectedSigner = (string) old('signatures.' . $roleKey, $storedSignatures[$roleKey]['id'] ?? ''); @endphp
                                <x-fi.field :label="$roleLabel" for="signatures-{{ $roleKey }}-{{ $recap->id }}">
                                    <x-fi.select id="signatures-{{ $roleKey }}-{{ $recap->id }}" name="signatures[{{ $roleKey }}]"
                                        prefix-icon="user" placeholder="-- Pilih penanda tangan --" data-fi-select="search">
                                        @foreach ($executives as $executive)
                                            <option value="{{ $executive->id }}" @selected($selectedSigner === (string) $executive->id)>
                                                {{ $executive->name }}{{ $executive->position ? ' - ' . $executive->position : '' }}
                                            </option>
                                        @endforeach
                                    </x-fi.select>
                                </x-fi.field>
                            @endforeach
                        </div>
                    </x-fi.section>
                @endif
            </div>

            {{-- SECTION: Aksi Form (kanan bawah: [Batal] [Simpan]) --}}
            <div class="flex flex-wrap items-center justify-end gap-3">
                <x-fi.button color="gray" :href="$indexUrl">Batal</x-fi.button>
                <x-fi.button type="submit" id="pfr-submit">{{ $isEdit ? 'Simpan Perubahan' : 'Simpan' }}</x-fi.button>
            </div>
        </form>
    </div>

